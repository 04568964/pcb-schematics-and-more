static uint16_t adc_read_raw(void) {
    uint16_t val = 0;
    HAL_ADC_Start(&hadc1);
    if (HAL_ADC_PollForConversion(&hadc1, 10) == HAL_OK) {
        val = (uint16_t)HAL_ADC_GetValue(&hadc1);
    }
    HAL_ADC_Stop(&hadc1);
    return val;
}
static uint8_t scale8(uint8_t val, uint8_t scale) {
    return (uint8_t)(((uint16_t)val * scale) >> 8);
}
static rgb_t color_wheel(uint8_t h){
  rgb_t c;
  if (h < 85U){
    c.r = 255U - h * 3U;
    c.g =  h * 3U;
    c.b = 0;
  }
  else if (h < 170U){
    h -= 85U;
    c.r = 0;
    c.g = 255U - h * 3U;
    c.b = h * 3U;
  }
  else{
    h -= 170U;
    c.r = h * 3U;
    c.g = 0;
    c.b = 255U - h * 3U;
  }
  return c;
}

